#!/usr/bin/env python3
"""Rebuild tests/sim/italyfull_data.h (42-italysim-full) from the Mod: Italy 2026-27 as 4.2 lays it out (the Mod's
tools/italy42.py: Serie D 9 x 18, the 6 pool clubs in their real groups), as bytes and numbers only, no names.

- the knockouts: the pack's ko_playoffs compiled by the Mod's gplay.compile_spec, every Serie D group at 18 clubs
  (the play-outs 13th v 16th, 14th v 15th: the pack's own 18-club shape, which 4.2 gives all nine groups);
- the divisions' promoted / relegated counts (the pack's);
- each club of Serie A .. D: its level, its division, its area bytes at the two levels of groups (mkseason.area_byte),
  its first team when it is a B team (clubs.csv 'second_of') and the B teams' rule (mkseason.SECOND_RULES['ita']).

    python3 -I tests/sim/mkitalyfull.py MOD [DATA]

MOD: a swos-9697-mod checkout (tools/gplay.py, mkseason.py, italy42.py); DATA: the world data (default: italy42's)."""
import csv
import json
import os
import sys

if len(sys.argv) < 2:
    sys.exit(__doc__)
mod = sys.argv[1]
sys.path.insert(0, os.path.join(mod, 'tools'))
import gplay  # noqa: E402  (the Mod's)
import italy42  # noqa: E402
import mkseason  # noqa: E402
data = sys.argv[2] if len(sys.argv) > 2 else italy42.DATA
d = os.path.join(data, 'ita')
pack = json.load(open(os.path.join(d, 'pack.json'), encoding='utf-8'))
lg = pack['competitions'][0]
divs = lg['divisions']
FIRST_D, GROUPS = italy42.FIRST_D, italy42.GROUPS
shape18 = next(po['entrants'] for po in lg['ko_playoffs'] if po['key'] == 'dD_playout')   # (an 18-club group's)
pos = []
for po in lg['ko_playoffs']:
    po = dict(po)
    if po['key'].startswith('d') and po['key'].endswith('_playout'):
        g = po['entrants'][0][0]
        po['entrants'] = [[g, p] for _, p in shape18]
    pos.append(po)
spec = gplay.compile_spec(pos, len(divs), lg.get('names'))

lay = italy42.layout(data)
rows = {r['key']: r for r in csv.DictReader(open(os.path.join(d, 'clubs.csv'), encoding='utf-8'))}
clubs = []                                  # (key, division)
for k in lay['A']:
    clubs.append((k, int(rows[k]['division'])))
for gi, g in enumerate(sorted(lay['groups'])):
    for k in lay['groups'][g]:
        clubs.append((k, FIRST_D + gi))
idx = {k: i for i, (k, _) in enumerate(clubs)}


def areas(k):
    a = rows[k]['area']
    c, _, dd = a.partition('/')
    return mkseason.area_byte(c), mkseason.area_byte(dd)


top, po_ok = mkseason.SECOND_RULES['ita']
out = ['/* Generated by tests/sim/mkitalyfull.py from the Mod (%s, data %s): do not edit. */' % (
           os.path.basename(os.path.abspath(mod)), os.path.basename(data)),
       '#define ITF_NDIV %d' % len(divs),
       '#define ITF_NCLUB %d' % len(clubs),
       '#define ITF_SECOND_TOP %d    /* the highest level a B team may reach (mkseason.SECOND_RULES) */' % top,
       '#define ITF_SECOND_PO %d     /* B teams may play the play-offs */' % (1 if po_ok else 0),
       'static const uint8_t ITF_PROM[ITF_NDIV] = { %s };' % ', '.join(str(x.get('promoted', 0)) for x in divs),
       'static const uint8_t ITF_REL[ITF_NDIV] = { %s };' % ', '.join(str(x.get('relegated', 0)) for x in divs),
       'static const uint8_t ITF_SIZE[ITF_NDIV] = { %s };' % ', '.join(
           str(x['teams'] if i < FIRST_D else italy42.GROUP_SIZE) for i, x in enumerate(divs)),
       '/* each club: division at the start, area byte at Serie C\'s level, at Serie D\'s, first team (FFFFh: none) */',
       'static const struct { uint8_t div, area_c, area_d; uint16_t first; } ITF_CLUB[ITF_NCLUB] = {']
for k, dv in clubs:
    ac, ad = areas(k)
    f = rows[k].get('second_of') or ''
    out.append('    { %d, 0x%02X, 0x%02X, 0x%04X },' % (dv, ac, ad, idx[f] if f in idx else 0xFFFF))
out.append('};')
out.append('static const uint8_t ITF_SPEC[%d] = {' % len(spec))
for i in range(0, len(spec), 20):
    out.append('    ' + ', '.join('%d' % b for b in spec[i:i + 20]) + ',')
out.append('};')
dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'italyfull_data.h')
open(dst, 'w').write('\n'.join(out) + '\n')
print('%s: %d clubs, %d divisions, spec %d bytes, B teams %d' % (
    dst, len(clubs), len(divs), len(spec), sum(1 for k, _ in clubs if rows[k].get('second_of'))))
