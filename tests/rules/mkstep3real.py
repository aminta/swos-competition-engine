#!/usr/bin/env python3
"""Rebuild tests/rules/step3real_data.h (EN step 3, the real-data chain test) from the Mod's 4.2 non-league data:
England's 164 (Premier League .. National League North / South) and the 88 step-3 clubs of 2026-27, as bytes and
numbers only, no names.

- division: the Mod's world order, 0 Premier League .. 3 League Two, 4 National League, 5 N, 6 S, 7..10 the step-3
  divisions N C S I (NPL, SPL Central, SPL South, Isthmian Premier);
- ns: the club's area byte at N / S, s3: at step 3 (low nibble the 1st choice, high nibble the 2nd + 1, F: none);
- rank: the ground's north-south rank byte (0 north .. 254; MC 08/11: round((55.90 - lat) / 6.00 * 255));
- strength: hundredths of the club's strength target (the Mod's nonleague levels: NL 7.76 .. 4.76, N / S 5.26 ..
  2.76, step 3 2.50 .. ; League Two, above the chain: 800).

    python3 -I tests/rules/mkstep3real.py DATA > tests/rules/step3real_data.h

DATA: the Mod's internal/nonleague2627 (step3/pg.csv, step3/nsrank.csv, levels.csv, step3/levels.csv)."""
import csv
import os
import sys


def rows(path):
    with open(path, newline='') as f:
        return list(csv.DictReader(f))


def main():
    data = sys.argv[1]
    pg = rows(os.path.join(data, 'step3', 'pg.csv'))
    tm = {r['key']: r['tm'] for r in rows(os.path.join(data, 'step3', 'nsrank.csv'))}
    target = {r['tm']: float(r['target']) for r in rows(os.path.join(data, 'levels.csv'))}
    target.update({r['tm']: float(r['target']) for r in rows(os.path.join(data, 'step3', 'levels.csv'))})
    out = []
    for r in sorted(pg, key=lambda r: int(r['ident'])):
        d = int(r['division'])
        if d < 3:
            continue
        if d == 3:
            s = 800
        else:
            t = target.get(tm.get(r['key']))
            assert t is not None, ('no strength target', r['key'])
            s = round(t * 100)
        rk = int(r['rank']) if r['rank'] != '' else 255
        assert 0 <= rk <= 255
        out.append((d, int(r['ns_byte'], 16), int(r['s3_byte'], 16), rk, s))
    cnt = {d: sum(1 for o in out if o[0] == d) for d in range(3, 11)}
    assert cnt == {3: 24, 4: 24, 5: 24, 6: 24, 7: 22, 8: 22, 9: 22, 10: 22}, cnt
    print('/* Generated by tests/rules/mkstep3real.py from the Mod (internal/nonleague2627, 4.2 non-league): do not edit. */')
    print(f'#define S3R_N {len(out)}')
    print('/* each club: division (3 League Two .. 10), ns area byte, step-3 area byte, rank, strength */')
    print('static const struct { uint8_t div, ns, s3, rank; uint16_t str; } S3R[S3R_N] = {')
    for i in range(0, len(out), 6):
        print('    ' + ' '.join('{ %d, 0x%02X, 0x%02X, %d, %d },' % o for o in out[i:i + 6]))
    print('};')


if __name__ == '__main__':
    main()
