#!/usr/bin/env python3
"""42-s2ko: the Coppa Italia / Supercoppa test inputs for tests/rules/s2ko.c -- tests/specs/ok/v14_ita_cups.json
(the competitions: 'numbers' groups, 'first_season', the bracket) and tests/rules/ita_cups_2526.json (the 2025-26
season end, the 2026-27 ties played) as a C header.

    python3 -I tests/rules/s2ko.py OUT.h

This stands in for the exe glue that will read the season end: each 'numbers' item is resolved here into its list
of last season's clubs ("<league>#N-M" = the table's places, the others = the fixture's lists); the selection
(skips, eligibility, order, the 'else', an unknown fact's fallback) is the library's, sr_kn_number."""
import json
import os
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
spec = json.load(open(os.path.join(HERE, '..', 'specs', 'ok', 'v14_ita_cups.json'), encoding='utf-8'))
fx = json.load(open(os.path.join(HERE, 'ita_cups_2526.json'), encoding='utf-8'))
HOMES = ['draw', 'better_placed', 'better_placed_second_leg', 'neutral', 'fixed', 'lower_number', 'lower_number_second_leg']
ORD = {'list': 0, 'record': 1, 'place_record': 2}
LEAGUES = ['ita.a', 'ita.b', 'ita.c-a', 'ita.c-b', 'ita.c-c']

ids = [c['id'][len('club:ita.'):] for c in spec['clubs']]
for t in fx['tables'].values():                     # (last season's clubs that are not in the world this season)
    ids += [r[0] for r in t if r[0] not in ids]
code = {k: i for i, k in enumerate(ids)}
comps = {c['id']: c for c in spec['competitions']}
elig = [0] * len(ids)
for lg in LEAGUES:
    for c in comps[lg]['participants']['clubs']:
        elig[code[c[len('club:ita.'):]]] = 1
rec = [(0, 0, 0, 0, 0)] * len(ids)
for t in fx['tables'].values():
    for p, (k, pts, pld, won, gf) in enumerate(t):
        rec[code[k]] = (pts, pld, won, gf, p + 1)


def resolve(ref):
    if isinstance(ref, list):                       # (a fallback: tables merged)
        return [k for r in ref for k in resolve(r)]
    if '#' in ref:
        lg, pos = ref.split('#')
        a, _, b = pos.partition('-')
        return [r[0] for r in fx['tables'][lg][int(a) - 1:int(b or a)]]
    return fx['lists'].get(ref, [])


# A list per ref, with its 'unknown' fallback's list (the stage's own: a non-table ref is named "<tag>:<ref>" past
# the first stage, so the Supercoppa's fallbacks are its own); -1 none.
lists, lidx = [], {}
def lid(ref, tag, unk):
    name = '+'.join(ref) if isinstance(ref, list) else ref
    key = name if '#' in name or tag == 'ci' else tag + ':' + name
    if key not in lidx:
        lidx[key] = len(lists)
        lists.append([key, [code[k] for k in resolve(ref)], -1])
        fb = unk.get(name) if isinstance(ref, str) else None
        if fb is not None and fb != 'none':
            lists[lidx[key]][2] = lid(fb, tag, unk)
    return lidx[key]


out = ['/* generated by tests/rules/s2ko.py: do not edit */', '#define S2_NCLUBS %d' % len(ids),
       'static const char *const s2_name[] = { %s };' % ', '.join('"%s"' % k for k in ids),
       'static const uint8_t s2_elig[] = { %s };' % ', '.join(map(str, elig)),
       'static const sr_kn_rec s2_rec[] = { %s };' % ', '.join('{ %d, %d, %d, %d, %d }' % r for r in rec)]
for cid, tag in (('ita.coppa', 'ci'), ('ita.supercoppa', 'sc')):
    st = comps[cid]['stages'][0]
    gs, unk = [], st.get('unknown', {})
    for g in st['numbers']:
        fr = [lid(x, tag, unk) for x in g['from']]
        el = [lid(x, tag, unk) for x in g.get('else', [])]
        gs.append('{ %d, %d, %d, %d, %d, { %s }, { %s } }' % (g['take'], ORD[g.get('order', 'list')],
                  ORD[g.get('else_order', 'list')], len(fr), len(el), ', '.join(map(str, fr)) or '0',
                  ', '.join(map(str, el)) or '0'))
    out.append('static const sr_kn_group s2_%s_groups[] = { %s };' % (tag, ', '.join(gs)))
    out.append('static const uint16_t s2_%s_first[] = { %s };' % (tag, ', '.join(
        str(code[k[len('club:ita.'):]]) for k in st['first_season']['numbers'])))
    rd, pairs, swap = [], [], []
    sw = set(st['first_season'].get('swap_home', []))

    def side(x):
        if x.startswith('#'):
            return x[1:]
        r, t = x[len('winner:'):].split('.')
        return 'SR_KN_WIN(%d, %d)' % (int(r) - 1, int(t) - 1)
    for ri, r in enumerate(st['rounds']):
        rd.append('{ %d, %d, %d, %d }' % (r['ties'], len(pairs), r['legs'], HOMES.index(r['home'])))
        for ti, (a, b) in enumerate(r['fixed']):
            pairs.append('{ %s, %s }' % (side(a), side(b)))
            swap.append('1' if '%d.%d' % (ri + 1, ti + 1) in sw else '0')
    out += ['static const sr_kn_round s2_%s_rounds[] = { %s };' % (tag, ', '.join(rd)),
            'static const sr_kn_pair s2_%s_pairs[] = { %s };' % (tag, ', '.join(pairs)),
            'static const uint8_t s2_%s_swap[] = { %s };' % (tag, ', '.join(swap)),
            '#define S2_%s_NG %d' % (tag.upper(), len(gs)), '#define S2_%s_NR %d' % (tag.upper(), len(rd)),
            '#define S2_%s_NP %d' % (tag.upper(), len(pairs)),
            '#define S2_%s_N %d' % (tag.upper(), len(st['first_season']['numbers']))]
# 42-s2ko M2: the Coppa Italia Serie C -- every club's town (1/100 degree), the zones' centres, round 1's clubs as
# numbered (C.U. 1/CIT, its groups in order), the seeds (round 2's listed clubs), the first season's rounds as pairs of
# numbers into s2c_num, then the drawn rounds; the real results (it.wikipedia: [round, home, away, winner])
cc = comps['ita.coppa-c']['stages'][0]
out.append('static const sr_kn_geo s2c_geo[] = { %s };' % ', '.join(
    '{ %d, %d }' % (round(c['geo'][0] * 100), round(c['geo'][1] * 100)) if 'geo' in c else '{ 0, 0 }'
    for c in (next((x for x in spec['clubs'] if x['id'] == 'club:ita.' + k), {}) for k in ids)))
out.append('static const sr_kn_geo s2c_centre[] = { %s };' % ', '.join('{ %d, %d }' % (round(a * 100), round(b * 100)) for a, b in cc['zones']['centres']))
cz = cc['first_season']['zones']
r1 = [code[k[len('club:ita.'):]] for z in cz for k in z]
out.append('static const uint16_t s2c_r1[] = { %s };' % ', '.join(map(str, r1)))
out.append('static const uint8_t s2c_r1zone[] = { %s };' % ', '.join(str(i) for i, z in enumerate(cz) for _ in z))
fr = cc['first_season']['rounds']
seeds = [(code[x[len('club:ita.'):]], ti // (len(fr[1]) // len(cz))) for ti, p in enumerate(fr[1]) for x in p if x.startswith('club:')]
out.append('static const uint16_t s2c_seed[] = { %s };' % ', '.join(str(c) for c, _ in seeds))
out.append('static const uint8_t s2c_seedzone[] = { %s };' % ', '.join(str(z) for _, z in seeds))
num = r1 + [c for c, _ in seeds]
def cside(x):
    if x.startswith('club:'):
        return str(num.index(code[x[len('club:ita.'):]]) + 1)
    r, t = x[len('winner:'):].split('.')
    return 'SR_KN_WIN(%d, %d)' % (int(r) - 1, int(t) - 1)
PR = {'fixed': 0, 'draw': 1, 'zone': 2}
crd, cpr, at = [], [], 0
for ri, r in enumerate(cc['rounds']):
    fixed = ri < len(fr)
    at += cc['rounds'][ri - 1]['ties'] if ri else 0
    crd.append('{ %d, %d, %d, %d, %d, 0, 0, 0 }' % (r['ties'], at, r['legs'], 4 if fixed else HOMES.index(r['home']),
                                                0 if fixed else PR[r['pairing']]))
    if fixed: cpr += ['{ %s, %s }' % (cside(a), cside(b)) for a, b in fr[ri]]
out += ['static const sr_kn_round s2c_rounds[] = { %s };' % ', '.join(crd),
        'static const sr_kn_pair s2c_pairs[] = { %s };' % ', '.join(cpr),
        'static const uint16_t s2c_num[] = { %s };' % ', '.join(map(str, num)),
        '#define S2C_NR %d' % len(crd), '#define S2C_NNUM %d' % len(num), '#define S2C_NZ %d' % len(cz),
        '#define S2C_NFIXED %d' % len(fr)]
cres = fx['coppa_c_2627']
out.append('static const uint16_t s2c_res[][4] = { %s };' % ', '.join('{ %d, %d, %d, %d }' % (
    r, code[h], code[a], code[w]) for r, h, a, w in cres))
out.append('#define S2C_NRES %d' % len(cres))
# 42-s2ko M2b: the Coppa Italia Serie D -- the first season's numbers (entry order: the preliminary's 68, then the
# others), its rounds 1-6 as drawn (pairs of numbers / earlier winners, home first as played), the played ties; the
# later seasons' shape (groups, blocks, homes) as the spec writes it, checked here and rebuilt in s2ko.c
cdd = comps['ita.coppa-d']['stages'][0]
cfs = cdd['first_season']
dnum = [code[k[len('club:ita.'):]] for k in cfs['numbers']]
def dside(x):
    if x.startswith('club:'):
        return str(dnum.index(code[x[len('club:ita.'):]]) + 1)
    r, t = x[len('winner:'):].split('.')
    return 'SR_KN_WIN(%d, %d)' % (int(r) - 1, int(t) - 1)
drd, dpr, at = [], [], 0
for ri, r in enumerate(cdd['rounds']):
    fixed = ri < len(cfs['rounds'])
    drd.append('{ %d, %d, %d, %d, %d, 0, 0, 0 }' % (r['ties'], at, r['legs'], 4 if fixed else HOMES.index(r['home']), 0 if fixed else 1))
    if fixed: dpr += ['{ %s, %s }' % (dside(a), dside(b)) for a, b in cfs['rounds'][ri]]
    at += r['ties']
G = ['ita.d-' + L for L in 'abcdefghi']
ng = cdd['numbers']
assert [g['take'] for g in ng] == [68, 94] and ng[0]['from'] == [x + ':new' for x in G] and ng[0]['else'] == [x + '#1-18' for x in G]
assert ng[0]['else_order'] == 'place_desc' and ng[1]['from'] == ng[0]['else'] and ng[1]['else'] == ng[0]['from']
shape = [(r['ties'], r['legs'], r['home'], r['pairing'], r.get('block', 0), r.get('numbers', '')) for r in cdd['rounds']]
assert shape[:2] == [(34, 1, 'draw', 'geo', 2, '1-68'), (64, 1, 'draw', 'geo', 4, '69-162')], shape
assert [x[2:4] for x in shape[2:]] == [('draw', 'fixed')] + [('alternate', 'fixed')] * 3 + [('draw', 'draw')] * 2, shape
for ri in range(2, 6):
    assert cdd['rounds'][ri]['fixed'] == [['winner:%d.%d' % (ri, 2 * t + 1), 'winner:%d.%d' % (ri, 2 * t + 2)] for t in range(shape[ri][0])]
cres = fx['coppa_d_2627']
out += ['static const sr_kn_round s2d_rounds[] = { %s };' % ', '.join(drd),
        'static const sr_kn_pair s2d_pairs[] = { %s };' % ', '.join(dpr),
        'static const uint16_t s2d_num[] = { %s };' % ', '.join(map(str, dnum)),
        'static const uint16_t s2d_res[][4] = { %s };' % ', '.join('{ %d, %d, %d, %d }' % (r, code[h], code[a], code[w]) for r, h, a, w in cres),
        '#define S2D_NR %d' % len(drd), '#define S2D_NFIXED %d' % len(cfs['rounds']), '#define S2D_NRES %d' % len(cres),
        '#define S2D_P %d' % shape[0][0], '#define S2D_R1 %d' % shape[1][0]]
out.append('#define S2_NLISTS %d' % len(lists))
for i, (ref, l, u) in enumerate(lists):
    out.append('static const uint16_t s2_l%d[] = { %s };   /* %s */' % (i, ', '.join(map(str, l)) or '0', ref))
out.append('static const sr_kn_list s2_lists0[] = { %s };' % ', '.join(
    '{ s2_l%d, %d, %d }' % (i, len(l), u) for i, (_, l, u) in enumerate(lists)))
out.append('static const char *const s2_lref[] = { %s };' % ', '.join('"%s"' % r for r, _, _ in lists))
ties = fx['ties2627']
out.append('static const uint16_t s2_ties[][4] = { %s };' % ', '.join('{ %d, %d, %d, %s }' % (
    r, code[h], code[a], code[w] if w else '0xFFFF') for r, h, a, w in ties))
out.append('#define S2_NTIES %d' % len(ties))
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
