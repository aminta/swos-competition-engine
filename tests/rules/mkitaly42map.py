#!/usr/bin/env python3
"""The old-save import's test data (42-s7reg): the SWOS 96/97 Mod's italy42 map (its tools/italy42.py, S7) as a C
fixture, tests/rules/italy42_map.h. Each club in import order -- today's file 102 rows by ordinal, then the off-file
pool clubs that come on (the 6 Serie D clubs in cupd.json's order, then the Eccellenza stand-ins in the reserve's) --
with its old word (0xFFFF: off the file), its 4.2 division (0..4 Serie A .. C, 5 + group Serie D, 0xFE a pool row)
and the word italy42.py gives it.

    python3 tests/rules/mkitaly42map.py ITALY42_CHECKOUT > tests/rules/italy42_map.h"""
import csv
import os
import sys


def main(mod):
    sys.path.insert(0, os.path.join(mod, 'tools'))
    import italy42 as m
    lay = m.layout()
    assert not m.check(lay), m.check(lay)
    rows = list(csv.DictReader(open(os.path.join(m.DATA, 'ita', 'clubs.csv'), encoding='utf-8')))
    olddiv = {r['key']: int(r['division']) for r in rows if r['file'] == 'league'}
    letters = sorted(lay['groups'])
    group = {k: g for g, ks in lay['groups'].items() for k in ks}
    byold = sorted(lay['old'], key=lambda k: lay['old'][k])
    out = []
    for k in byold:
        div = olddiv[k] if olddiv[k] < m.FIRST_D else m.FIRST_D + letters.index(group[k])
        f, o = lay['map'][(m.FILE_A, lay['old'][k])]
        out.append((m.FILE_A | lay['old'][k] << 8, div, f | o << 8))
    pool = [k for k in lay['B'] if k not in lay['old']]       # (the 6 at their groups' ends, then the reserve)
    for k in [k for k in pool if k in group] + [k for k in pool if k not in group]:
        div = m.FIRST_D + letters.index(group[k]) if k in group else 0xFE
        f, o = lay['map'][('pool', k)]
        out.append((0xFFFF, div, f | o << 8))
    print('/* generated by tests/rules/mkitaly42map.py from the Mod\'s tools/italy42.py (S7): old word, 4.2 division, '
          'new word */')
    print('#define I42_N %d' % len(out))
    print('#define I42_FILE_A %d' % m.FILE_A)
    print('#define I42_FILE_B %d' % m.FILE_B)
    print('static const struct { uint16_t old; uint8_t div; uint16_t word; } I42[I42_N] = {')
    for i in range(0, len(out), 6):
        print('    ' + ' '.join('{ 0x%04X, %d, 0x%04X },' % x for x in out[i:i + 6]))
    print('};')


if __name__ == '__main__':
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    main(sys.argv[1])
